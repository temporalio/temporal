// TestReplays replays every recorded history under the current binary, so a history an older
// server wrote still replays after an upgrade. It covers both the per-release version snapshots
// (versionReleases) and the targeted behavior fixtures (replay_with_*, replay_recent_*) that
// exercise specific version logic.
func TestReplays(t *testing.T) {
	files, err := filepath.Glob(filepath.Join("testdata", "replay_*.json.gz"))
	require.NoError(t, err)
	require.NotEmpty(t, files)
	for _, f := range files {
		t.Run(filepath.Base(f), func(t *testing.T) {
			for _, tc := range []struct {
				name            string
				maxIterations   int
				versionCeiling  int
				versionOverride int
			}{
				{name: "default", maxIterations: math.MaxInt, versionCeiling: -1, versionOverride: -1},
				{name: "lower-spec-limit", maxIterations: 1000, versionCeiling: -1, versionOverride: -1},
				{name: "ceiling-below-current", maxIterations: math.MaxInt, versionCeiling: int(scheduler.TriggerImmediatelyTimestamp) - 1, versionOverride: -1},
				{name: "ceiling-above-current", maxIterations: math.MaxInt, versionCeiling: int(scheduler.TriggerImmediatelyTimestamp) + 1, versionOverride: -1},
				{name: "override-latest", maxIterations: math.MaxInt, versionCeiling: -1, versionOverride: int(scheduler.LatestSchedulerWorkflowVersion)},
			} {
				t.Run(tc.name, func(t *testing.T) {
					replay(t, loadHistory(t, f), schedulerWorkflowForReplay(tc.maxIterations, tc.versionCeiling, tc.versionOverride))
				})
			}
		})
	}
}

// TestEveryVersionIsMapped checks every version from InitialVersion through
// LatestSchedulerWorkflowVersion maps to a fixture that is present, so a newly added version (e.g.
// bumping the default) can't escape replay coverage. Versions with no released server must map to
// a generated fixture that actually records that version.
func TestEveryVersionIsMapped(t *testing.T) {
	mapped := map[scheduler.SchedulerWorkflowVersion]string{}
	for _, vr := range versionReleases {
		name := vr.fixture
		if name == "" {
			name = "replay_" + vr.server + ".json.gz"
		}
		mapped[vr.version] = name
		_, err := os.Stat(filepath.Join("testdata", name))
		require.NoErrorf(t, err, "missing snapshot %s for scheduler v%d", name, int(vr.version))
	}
	for v := scheduler.InitialVersion; v <= scheduler.LatestSchedulerWorkflowVersion; v++ {
		require.Containsf(t, mapped, v, "scheduler version v%d is not mapped to a fixture in versionReleases", int(v))
	}
	// The newest version has no released-server snapshot; the fixture it maps to must actually
	// record that version, so the mapping can't silently point at a stale, lower-version history.
	latest := scheduler.LatestSchedulerWorkflowVersion
	versions := fixtureTweakablesVersions(t, filepath.Join("testdata", mapped[latest]))
	require.Containsf(t, versions, latest,
		"fixture %s does not record a v%d tweakables marker", mapped[latest], int(latest))
}

// fixtureTweakablesVersions returns the Version recorded in every "tweakables" MutableSideEffect
// marker in the fixture. It mirrors the decode in tests/scheduler_replay_generation_test.go.
func fixtureTweakablesVersions(t *testing.T, path string) []scheduler.SchedulerWorkflowVersion {
	t.Helper()
	h := loadHistory(t, path)
	var out []scheduler.SchedulerWorkflowVersion
	for _, event := range h.GetEvents() {
		attrs := event.GetMarkerRecordedEventAttributes()
		if attrs.GetMarkerName() != "MutableSideEffect" {
			continue
		}
		data := attrs.GetDetails()["data"].GetPayloads()
		if len(data) != 2 {
			continue
		}
		var id string
		if payload.Decode(data[0], &id) != nil || id != "tweakables" {
			continue
		}
		var payloads commonpb.Payloads
		if proto.Unmarshal(data[1].GetData(), &payloads) != nil || len(payloads.GetPayloads()) != 1 {
			continue
		}
		var tweakables scheduler.TweakablePolicies
		if payload.Decode(payloads.GetPayloads()[0], &tweakables) != nil {
			continue
		}
		out = append(out, tweakables.Version)
	}
	return out
}

