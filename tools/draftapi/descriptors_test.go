func TestMissingMapping(t *testing.T) {
	message := &descriptorpb.DescriptorProto{Name: proto.String("Draft"), Options: &descriptorpb.MessageOptions{}}
	setVetDraftOption(message.Options, 12345, "feature")
	c := mappingCatalog()
	fd := &descriptorpb.FileDescriptorProto{Name: proto.String("test.proto"), MessageType: []*descriptorpb.DescriptorProto{message}}
	require.ErrorContains(t, c.checkMappings(fd), "cannot map draft message Draft to Go")
	c.seen[message] = true
	require.NoError(t, c.checkMappings(fd))
}

func mappingCatalog() *catalog {
	return &catalog{
		options: []option{{Extendee: "google.protobuf.MessageOptions", Number: 12345}, {Extendee: "google.protobuf.EnumOptions", Number: 12346}},
		seen:    make(map[proto.Message]bool),
	}
}

func TestMissingEnumMapping(t *testing.T) {
	enum := &descriptorpb.EnumDescriptorProto{Name: proto.String("DraftEnum"), Options: &descriptorpb.EnumOptions{}}
	setVetDraftOption(enum.Options, 12346, "feature")
	fd := &descriptorpb.FileDescriptorProto{Name: proto.String("test.proto"), EnumType: []*descriptorpb.EnumDescriptorProto{enum}}
	require.ErrorContains(t, mappingCatalog().checkMappings(fd), "cannot map draft enum DraftEnum to Go")
}

func TestMissingNestedAnnotatedMapping(t *testing.T) {
	nested := &descriptorpb.DescriptorProto{Name: proto.String("Nested"), Options: &descriptorpb.MessageOptions{}}
	setVetDraftOption(nested.Options, 12345, "feature")
	parent := &descriptorpb.DescriptorProto{Name: proto.String("Parent"), NestedType: []*descriptorpb.DescriptorProto{nested}}
	fd := &descriptorpb.FileDescriptorProto{Name: proto.String("test.proto"), MessageType: []*descriptorpb.DescriptorProto{parent}}
	c := mappingCatalog()
	c.seen[parent] = true
	require.ErrorContains(t, c.checkMappings(fd), "cannot map draft message Nested to Go")
}

// Unannotated declarations nested in a draft message inherit its gate, so they need a mapping too.
func TestMissingNestedInheritedMapping(t *testing.T) {
	nested := &descriptorpb.DescriptorProto{Name: proto.String("Nested")}
	enum := &descriptorpb.EnumDescriptorProto{Name: proto.String("NestedEnum")}
	parent := &descriptorpb.DescriptorProto{Name: proto.String("Parent"), Options: &descriptorpb.MessageOptions{},
		NestedType: []*descriptorpb.DescriptorProto{nested}, EnumType: []*descriptorpb.EnumDescriptorProto{enum}}
	setVetDraftOption(parent.Options, 12345, "feature")
	fd := &descriptorpb.FileDescriptorProto{Name: proto.String("test.proto"), MessageType: []*descriptorpb.DescriptorProto{parent}}
	c := mappingCatalog()
	c.seen[parent] = true
	c.seen[nested] = true
	require.ErrorContains(t, c.checkMappings(fd), "cannot map draft enum NestedEnum to Go")
	c.seen[enum] = true
	delete(c.seen, nested)
	require.ErrorContains(t, c.checkMappings(fd), "cannot map draft message Nested to Go")
}

// draftFixture returns the real draft option schema and a file with one message, Message,
// whose fields draft (1) and notes (2) match the Go struct generated by runDraftFixture.
func draftFixture() (schema, file *descriptorpb.FileDescriptorProto) {
	schema = protodesc.ToFileDescriptorProto(protometapb.File_temporal_api_next_protometa_v1_draft_proto)
	file = &descriptorpb.FileDescriptorProto{
		Name: proto.String("message.proto"), Package: proto.String("temporal.api.test.v1"),
		Dependency: []string{schema.GetName()}, Options: &descriptorpb.FileOptions{},
		MessageType: []*descriptorpb.DescriptorProto{{
			Name: proto.String("Message"), Options: &descriptorpb.MessageOptions{},
			Field: []*descriptorpb.FieldDescriptorProto{
				{Name: proto.String("draft"), Number: proto.Int32(1), Options: &descriptorpb.FieldOptions{}},
				{Name: proto.String("notes"), Number: proto.Int32(2), Options: &descriptorpb.FieldOptions{}},
			},
		}},
	}
	return schema, file
}

// runDraftFixture runs Analyzer on one generated API package holding both descriptors. It
// returns the diagnostics and the exported features by symbol.
func runDraftFixture(t *testing.T, schema, file *descriptorpb.FileDescriptorProto) ([]string, map[string][]string) {
	t.Helper()
	var source strings.Builder
	source.WriteString("// Code generated by fixture. DO NOT EDIT.\npackage test\n")
	source.WriteString("type Message struct {\nDraft string `protobuf:\"bytes,1,opt,name=draft,proto3\"`\nNotes string `protobuf:\"bytes,2,opt,name=notes,proto3\"`\n}\n")
	for name, fd := range map[string]*descriptorpb.FileDescriptorProto{"schema": schema, "message": file} {
		data, err := proto.Marshal(fd)
		require.NoError(t, err)
		fmt.Fprintf(&source, "const file_%s_rawDesc = %q\n", name, data)
	}
	source.WriteString("func file_message_rawDescGZIP() []byte { return []byte(file_message_rawDesc) }\n")
	source.WriteString("func (*Message) Descriptor() ([]byte, []int) { return file_message_rawDescGZIP(), []int{0} }\n")
	pass := descriptorPass(t, source.String())
	var diagnostics []string
	facts := make(map[string][]string)
	pass.Report = func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d.Message) }
	pass.ImportPackageFact = func(*types.Package, analysis.Fact) bool { return false }
	pass.ImportObjectFact = func(types.Object, analysis.Fact) bool { return false }
	pass.ExportPackageFact = func(analysis.Fact) {}
	pass.ExportObjectFact = func(_ types.Object, fact analysis.Fact) {
		facts[fact.(*apiFact).Symbol] = fact.(*apiFact).Features
	}
	_, err := Analyzer.Run(pass)
	require.NoError(t, err)
	return diagnostics, facts
}

// The test binary links the real option schema, so descriptors decode the options as
// registered extensions rather than unknown fields.
func TestRegisteredDraftOptions(t *testing.T) {
	schema, file := draftFixture()
	proto.SetExtension(file.MessageType[0].Field[0].Options, protometapb.E_Draft, "field-feature")
	proto.SetExtension(file.MessageType[0].Options, protometapb.E_DraftMessage, "message-feature")
	// Every real draft option shares one number, so an unrelated option with that number
	// on another extendee must not be read as a draft annotation.
	setVetDraftOption(file.Options, protowire.Number(protometapb.E_Draft.TypeDescriptor().Number()), "unrelated value")

	data, err := proto.Marshal(file)
	require.NoError(t, err)
	decoded := new(descriptorpb.FileDescriptorProto)
	require.NoError(t, proto.Unmarshal(data, decoded))
	require.Empty(t, decoded.MessageType[0].Field[0].Options.ProtoReflect().GetUnknown())

	diagnostics, facts := runDraftFixture(t, schema, file)
	require.Empty(t, diagnostics)
	require.Equal(t, []string{"message-feature"}, facts["go.temporal.io/api/test/v1.Message"])
	require.Equal(t, []string{"field-feature", "message-feature"}, facts["go.temporal.io/api/test/v1.Message.Draft"])
	require.Equal(t, []string{"message-feature"}, facts["go.temporal.io/api/test/v1.Message.Notes"])
}

func TestDraftOptionDiscovery(t *testing.T) {
	number := protowire.Number(protometapb.E_Draft.TypeDescriptor().Number())
	for _, tc := range []struct {
		name   string
		mutate func(schema, file *descriptorpb.FileDescriptorProto)
		want   string
	}{
		{name: "notes-impostor", mutate: func(schema, file *descriptorpb.FileDescriptorProto) {
			// A draft-prefixed name outside the option table is not a draft option.
			schema.Extension = append(schema.Extension, &descriptorpb.FieldDescriptorProto{
				Name: proto.String("draft_notes"), Number: proto.Int32(98009), Extendee: proto.String(".google.protobuf.FieldOptions"),
				Label: descriptorpb.FieldDescriptorProto_LABEL_OPTIONAL.Enum(), Type: descriptorpb.FieldDescriptorProto_TYPE_STRING.Enum(),
			})
			setVetDraftOption(file.MessageType[0].Field[0].Options, 98009, "free text with spaces")
			setVetDraftOption(file.MessageType[0].Field[1].Options, 98009, "token")
		}},
		{name: "wrong-extendee", mutate: func(schema, _ *descriptorpb.FileDescriptorProto) {
			schema.Extension[0].Extendee = proto.String(".google.protobuf.MessageOptions")
		}, want: "draft option draft must be a singular string extending google.protobuf.FieldOptions"},
		{name: "repeated", mutate: func(schema, _ *descriptorpb.FileDescriptorProto) {
			schema.Extension[0].Label = descriptorpb.FieldDescriptorProto_LABEL_REPEATED.Enum()
		}, want: "draft option draft must be a singular string extending google.protobuf.FieldOptions"},
		{name: "public-import", mutate: func(_, file *descriptorpb.FileDescriptorProto) {
			file.PublicDependency = []int32{0}
			setVetDraftOption(file.MessageType[0].Field[0].Options, number, "feature")
		}, want: "message.proto: public import of temporal/api_next/protometa/v1/draft.proto is not supported; import it directly"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			schema, file := draftFixture()
			require.Equal(t, "draft", schema.Extension[0].GetName())
			tc.mutate(schema, file)
			diagnostics, facts := runDraftFixture(t, schema, file)
			if tc.want == "" {
				require.Empty(t, diagnostics)
				require.Empty(t, facts)
				return
			}
			require.Len(t, diagnostics, 1)
			require.Contains(t, diagnostics[0], tc.want)
		})
	}
}
