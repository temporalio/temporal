func descriptorPass(t *testing.T, source string) *analysis.Pass {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "message.pb.go", source, parser.ParseComments)
	require.NoError(t, err)
	info := &types.Info{
		Types: make(map[ast.Expr]types.TypeAndValue),
		Defs:  make(map[*ast.Ident]types.Object),
		Uses:  make(map[*ast.Ident]types.Object),
	}
	config := types.Config{}
	pkg, err := config.Check("go.temporal.io/api/test/v1", fset, []*ast.File{file}, info)
	require.NoError(t, err)
	return &analysis.Pass{Fset: fset, Files: []*ast.File{file}, TypesInfo: info, Pkg: pkg}
}

func TestDescriptorBytes(t *testing.T) {
	for _, expr := range []string{`"\x08" + "\x01"`, `[]byte{0x08, 0x01}`} {
		t.Run(expr, func(t *testing.T) {
			pass := descriptorPass(t, "package test; var raw = "+expr)
			value := pass.Files[0].Decls[0].(*ast.GenDecl).Specs[0].(*ast.ValueSpec).Values[0]
			data, err := descriptorBytes(pass, value)
			require.NoError(t, err)
			require.Equal(t, []byte{8, 1}, data)
		})
	}
}

