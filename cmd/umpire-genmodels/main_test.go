func TestRenderToolEnvironmentRejectsInvalidTools(t *testing.T) {
	tests := []struct {
		name  string
		tools []verify.ToolVersion
		err   string
	}{
		{
			name: "environment identifier collision",
			tools: []verify.ToolVersion{
				{Name: "model-checker", Version: "1", URL: "https://tools.example/first", SHA256: "first-sha", Archive: "first", ArchiveType: "file", ExtractRoot: "first", Executable: "first/bin"},
				{Name: "model_checker", Version: "2", URL: "https://tools.example/second", SHA256: "second-sha", Archive: "second", ArchiveType: "file", ExtractRoot: "second", Executable: "second/bin"},
			},
			err: `tool names "model-checker" and "model_checker" share environment identifier "MODEL_CHECKER"`,
		},
		{
			name: "missing platform",
			tools: []verify.ToolVersion{{
				Name: "multi", Version: "1", Artifacts: []verify.ToolArtifact{{
					Platform: "darwin-universal2", URL: "https://tools.example/multi", SHA256: "multi-sha",
				}},
			}},
			err: `tool "multi" has no artifact for platform "linux-x86_64"`,
		},
		{
			name:  "missing version",
			tools: []verify.ToolVersion{{Name: "single", URL: "https://tools.example/single", SHA256: "single-sha"}},
			err:   `tool "single" has an empty version`,
		},
		{
			name:  "missing URL",
			tools: []verify.ToolVersion{{Name: "single", Version: "1", SHA256: "single-sha"}},
			err:   `tool "single" has an empty url`,
		},
		{
			name:  "missing checksum",
			tools: []verify.ToolVersion{{Name: "single", Version: "1", URL: "https://tools.example/single"}},
			err:   `tool "single" has an empty sha256`,
		},
		{
			name:  "missing installation metadata",
			tools: []verify.ToolVersion{{Name: "single", Version: "1", URL: "https://tools.example/single", SHA256: "single-sha"}},
			err:   `tool "single" has incomplete installation metadata`,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			_, err := renderToolEnvironment(test.tools, "linux-x86_64")
			require.EqualError(t, err, test.err)
		})
	}
}

