func weakenGeneratedProperty(t *testing.T, source string, backend runner.Backend, marker, replacement string) string {
	t.Helper()
	markerIndex := strings.Index(source, marker)
	require.NotEqual(t, -1, markerIndex, marker)
	if backend == runner.TLC || backend == runner.Apalache || backend == runner.Fizz {
		bodyStart := markerIndex + len(marker)
		bodyEnd := strings.Index(source[bodyStart:], "\n\n")
		require.NotEqual(t, -1, bodyEnd, marker)
		return source[:bodyStart] + replacement + source[bodyStart+bodyEnd:]
	}
	lineStart := strings.LastIndex(source[:markerIndex], "\n") + 1
	lineEnd := strings.Index(source[markerIndex:], "\n")
	require.NotEqual(t, -1, lineEnd, marker)
	return source[:lineStart] + replacement + source[markerIndex+lineEnd:]
}

func compareInterpreterOutcome(model verify.Model, maxDepth uint64, result verify.Result) error {
	interpreter, err := verify.NewInterpreter(model)
	if err != nil {
		return err
	}
	exploration, err := interpreter.Explore(maxDepth)
	if err != nil {
		return err
	}
	if len(exploration.Violations) != 0 && result.Status != verify.Counterexample {
		return fmt.Errorf("backend missed canonical counterexample for %q", exploration.Violations[0].Property)
	}
	return nil
}

