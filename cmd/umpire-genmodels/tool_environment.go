package main

import (
	"fmt"
	"slices"
	"strings"
	"unicode"

	"go.temporal.io/server/common/testing/umpire/verify"
)

func renderToolEnvironment(tools []verify.ToolVersion, platform string) ([]byte, error) {
	ordered := slices.Clone(tools)
	slices.SortFunc(ordered, func(left, right verify.ToolVersion) int {
		return strings.Compare(left.Name, right.Name)
	})
	identifiers := make(map[string]string, len(ordered))
	var output strings.Builder
	output.WriteString("# Code generated by umpire-genmodels. DO NOT EDIT.\n")
	for _, tool := range ordered {
		identifier := toolEnvironmentIdentifier(tool.Name)
		if previous, exists := identifiers[identifier]; exists {
			return nil, fmt.Errorf("tool names %q and %q share environment identifier %q", previous, tool.Name, identifier)
		}
		identifiers[identifier] = tool.Name
		artifact, err := toolArtifact(tool, platform)
		if err != nil {
			return nil, err
		}
		if tool.Version == "" {
			return nil, fmt.Errorf("tool %q has an empty version", tool.Name)
		}
		if artifact.URL == "" {
			return nil, fmt.Errorf("tool %q has an empty url", tool.Name)
		}
		if artifact.SHA256 == "" {
			return nil, fmt.Errorf("tool %q has an empty sha256", tool.Name)
		}
		if artifact.Archive == "" || artifact.ArchiveType == "" || artifact.ExtractRoot == "" || artifact.Executable == "" {
			return nil, fmt.Errorf("tool %q has incomplete installation metadata", tool.Name)
		}
		prefix := "UMPIRE_TOOL_" + identifier + "_"
		fmt.Fprintf(&output, "%sVERSION=%s\n", prefix, shellQuote(tool.Version))
		fmt.Fprintf(&output, "%sURL=%s\n", prefix, shellQuote(artifact.URL))
		fmt.Fprintf(&output, "%sSHA256=%s\n", prefix, shellQuote(artifact.SHA256))
		fmt.Fprintf(&output, "%sARCHIVE=%s\n", prefix, shellQuote(artifact.Archive))
		fmt.Fprintf(&output, "%sARCHIVE_TYPE=%s\n", prefix, shellQuote(artifact.ArchiveType))
		fmt.Fprintf(&output, "%sEXTRACT_ROOT=%s\n", prefix, shellQuote(artifact.ExtractRoot))
		fmt.Fprintf(&output, "%sPACKAGE=%s\n", prefix, shellQuote(artifact.Package))
		fmt.Fprintf(&output, "%sEXECUTABLE=%s\n", prefix, shellQuote(artifact.Executable))
	}
	return []byte(output.String()), nil
}

func toolArtifact(tool verify.ToolVersion, platform string) (verify.ToolArtifact, error) {
	if len(tool.Artifacts) == 0 {
		return verify.ToolArtifact{
			Platform: platform, URL: tool.URL, SHA256: tool.SHA256, Archive: tool.Archive,
			ArchiveType: tool.ArchiveType, ExtractRoot: tool.ExtractRoot, Package: tool.Package, Executable: tool.Executable,
		}, nil
	}
	for _, artifact := range tool.Artifacts {
		if artifact.Platform == platform {
			return artifact, nil
		}
	}
	return verify.ToolArtifact{}, fmt.Errorf("tool %q has no artifact for platform %q", tool.Name, platform)
}

func localToolPlatform(goos string, goarch string) (string, error) {
	architecture := goarch
	if architecture == "amd64" {
		architecture = "x86_64"
	}
	if (goos != "darwin" && goos != "linux") || (architecture != "arm64" && architecture != "x86_64") {
		return "", fmt.Errorf("unsupported local verification tool platform %q", goos+"-"+goarch)
	}
	return goos + "-" + architecture, nil
}

func toolEnvironmentIdentifier(name string) string {
	return strings.Map(func(value rune) rune {
		if unicode.IsLetter(value) || unicode.IsDigit(value) {
			return unicode.ToUpper(value)
		}
		return '_'
	}, name)
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'"
}
